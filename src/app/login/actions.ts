"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { createClient } from "@/lib/supabase/server";
import { prisma } from "@/lib/prisma";

export async function signInWithEmail(formData: FormData) {
  const supabase = await createClient();

  const email = String(formData.get("email") ?? "").trim();
  const password = String(formData.get("password") ?? "");

  const { data, error } = await supabase.auth.signInWithPassword({
    email,
    password,
  });

  if (error || !data.user) {
    return { error: "E-mail ou senha incorretos. Tente novamente." };
  }

  // Synchronize user in Prisma using the UUID generated by Supabase Auth
  await prisma.user.upsert({
    where: { id: data.user.id },
    update: {
      email: data.user.email!,
    },
    create: {
      id: data.user.id,
      email: data.user.email!,
      name:
        data.user.user_metadata?.full_name ??
        data.user.email!.split("@")[0],
    },
  });

  revalidatePath("/", "layout");
  redirect("/");
}

export async function signUpWithEmail(formData: FormData) {
  const supabase = await createClient();

  const name = String(formData.get("name") ?? "").trim();
  const email = String(formData.get("email") ?? "").trim();
  const password = String(formData.get("password") ?? "");

  if (password.length < 6) {
    return { error: "A senha deve ter pelo menos 6 caracteres." };
  }

  const { data, error } = await supabase.auth.signUp({
    email,
    password,
    options: {
      data: { full_name: name },
    },
  });

  if (error || !data.user) {
    return {
      error:
        error?.message ??
        "Não foi possível criar sua conta. Verifique os dados informados.",
    };
  }

  // Create the User row in PostgreSQL with the exact UUID from Supabase Auth
  await prisma.user.upsert({
    where: { id: data.user.id },
    update: {
      name: name || email.split("@")[0],
      email,
    },
    create: {
      id: data.user.id,
      name: name || email.split("@")[0],
      email,
    },
  });

  revalidatePath("/", "layout");
  redirect("/");
}

export async function signOutUser() {
  const supabase = await createClient();
  await supabase.auth.signOut();
  revalidatePath("/", "layout");
  redirect("/login");
}